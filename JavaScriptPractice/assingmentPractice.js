//1. write a program to find the sum of two numbers using let variable
let num1 = 5;
let num2 = 10;
let sum = num1 + num2;
console.log("The sum of", num1, "and", num2, "is:", sum); // Output: The sum of 5 and 10 is: 15

//2. write a program to find the subtraction of two numbers using let variable
let num3 = 15;
let num4 = 7;
let difference = num3 - num4;
console.log("The difference between", num3, "and", num4, "is:", difference); // Output: The difference between 15 and 7 is: 8
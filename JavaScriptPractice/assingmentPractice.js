//1. write a program to find the sum of two numbers using let variable
let num1 = 5;
let num2 = 10;
let sum = num1 + num2;
console.log("The sum of", num1, "and", num2, "is:", sum); // Output: The sum of 5 and 10 is: 15

//2. write a program to find the subtraction of two numbers using let variable
let num3 = 15;
let num4 = 7;
let difference = num3 - num4;
console.log("The difference between", num3, "and", num4, "is:", difference); // Output: The difference between 15 and 7 is: 8

//3. write a program to find the multiplication of two numbers using let variable
let num5 = 4;
let num6 = 6;
let product = num5 * num6;
console.log("The product of", num5, "and", num6, "is:", product); // Output: The product of 4 and 6 is: 24

//4. write a program to find the division of two numbers using let variable
let num7 = 20;
let num8 = 4;
let quotient = num7 / num8;
console.log("The quotient of", num7, "and", num8, "is:", quotient); // Output: The quotient of 20 and 4 is: 5